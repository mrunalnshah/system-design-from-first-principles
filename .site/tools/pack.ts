/**
 * TOOL-01 Context packer (plan/tools.md): bundles exactly what one task or one round needs,
 * so an agent loads a few thousand tokens instead of the whole plan.
 *
 * A bundle holds, in this order: the task packets (a round's packets in the round's order),
 * every `load:` section, the requirement sections the packets deliver, their module entries,
 * the current contents of the files they change, and the last 10 progress lines. Each piece
 * appears once even if several packets ask for it.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadPlan, type Packet } from "./plan.ts";

/** The repository root when the caller gives none: two folders up from `.site/tools/` (same rule as cli.ts). */
const defaultRoot = fileURLToPath(new URL("../../", import.meta.url));

export type PackResult = { text: string; tokens: number; warnings: string[] };

/**
 * Builds the bundle for `target` (a task ID like `T-00.03` or a round ID like `R-02`).
 * `tokens` is an estimate: characters ÷ 4, rounded up. A warning is returned (not thrown)
 * when the estimate is over the summed `context_budget_tokens` of the packets.
 * With `out`, the bundle is also written to that path (callers resolve it; the CLI uses the folder the user ran npm from).
 * Throws `Unknown task or round: <target>` for anything else.
 */
export function pack(target: string, opts: { out?: string; root?: string } = {}): PackResult {
  const root = opts.root ?? defaultRoot;
  const plan = loadPlan(root);
  const byId = new Map(plan.packets.map((p) => [p.id, p]));
  const round = plan.rounds.find((r) => r.id === target);
  const packets = round ? round.tasks.map((id) => byId.get(id)).filter((p): p is Packet => !!p) : byId.has(target) ? [byId.get(target)!] : [];
  if (!packets.length) throw new Error(`Unknown task or round: ${target}`);

  const parts: string[] = [`# Context pack: ${target}`, `Generated by \`tools pack ${target}\`. Temporary: don't commit it.`];
  const seen = new Set<string>();
  const once = (key: string, text: string | undefined) => {
    if (text === undefined || seen.has(key)) return;
    seen.add(key);
    parts.push(text.trimEnd());
  };

  parts.push("\n## Task packets");
  for (const p of packets) once(`packet:${p.id}`, read(root, p.path));

  parts.push("\n## Loaded sections");
  for (const p of packets) for (const item of list(p, "load")) once(`load:${item}`, loadItem(root, item));

  parts.push("\n## Requirements delivered");
  for (const p of packets) for (const id of list(p, "delivers")) {
    const found = requirementSection(root, id);
    if (found) once(`req:${found.key}`, found.text);
  }

  parts.push("\n## Module entries");
  for (const p of packets) {
    const mod = String(p.fields.module ?? "");
    if (mod.startsWith("MOD-")) once(`mod:${mod}`, sectionByAnchor(read(root, "specs/modules.md") ?? "", slugify(mod)) ?? `## ${mod}\n(not found in specs/modules.md)`);
  }

  parts.push("\n## Files this round changes (current contents)");
  // A file already loaded whole (a `load:` item without #anchor) isn't repeated here.
  for (const p of packets) for (const file of list(p, "files")) if (!seen.has(`load:${file}`)) once(`file:${file}`, fileBlock(root, file));

  parts.push("\n## Recent progress (last 10 lines)");
  const progress = (read(root, ".blueprint/progress.md") ?? "").split(/\r?\n/).filter((l) => l.trim() && !l.startsWith("#"));
  parts.push(progress.slice(-10).join("\n"));

  const text = parts.join("\n\n") + "\n";
  const tokens = Math.ceil(text.length / 4);
  const budget = packets.reduce((sum, p) => sum + Number(p.fields.context_budget_tokens ?? 0), 0);
  const warnings = budget && tokens > budget ? [`Bundle for ${target} is about ${tokens} tokens, over its budget of ${budget} tokens.`] : [];
  if (opts.out) writeFileSync(opts.out, text);
  return { text, tokens, warnings };
}

/** GitHub-style heading anchor: lowercase, punctuation removed (except `-` and `_`), spaces → `-`. */
export function slugify(heading: string): string {
  return heading.trim().toLowerCase().replace(/[^\p{L}\p{M}\p{N}_\- ]/gu, "").replace(/ /g, "-");
}

/**
 * The section under the heading whose anchor is `anchor`: the heading line and everything up to
 * the next heading of the same or a higher level. Headings inside fenced code blocks don't count.
 * Returns undefined when no heading has that anchor.
 */
export function sectionByAnchor(markdown: string, anchor: string): string | undefined {
  const lines = markdown.split(/\r?\n/);
  let inFence = false, start = -1, level = 0;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!;
    if (/^\s*(```|~~~)/.test(line)) inFence = !inFence;
    if (inFence) continue;
    const h = /^(#{1,6})\s+(.*)$/.exec(line);
    if (!h) continue;
    if (start >= 0 && h[1]!.length <= level) return lines.slice(start, i).join("\n").trimEnd();
    if (start < 0 && slugify(h[2]!) === anchor) { start = i; level = h[1]!.length; }
  }
  return start >= 0 ? lines.slice(start).join("\n").trimEnd() : undefined;
}

// ---------- internals ----------

function read(root: string, rel: string): string | undefined {
  const p = join(root, rel);
  return existsSync(p) && statSync(p).isFile() ? readFileSync(p, "utf8") : undefined;
}

function list(p: Packet, key: string): string[] {
  const v = p.fields[key];
  return Array.isArray(v) ? v : [];
}

/** `file.md#anchor` → that section; `file.md` → the whole file. Missing pieces are named, not dropped silently. */
function loadItem(root: string, item: string): string {
  const [file, anchor] = item.split("#") as [string, string | undefined];
  const text = read(root, file);
  if (text === undefined) return `### ${item}\n(not found: ${file} doesn't exist)`;
  if (!anchor) return `### ${file}\n\n${text.trimEnd()}`;
  return `### ${item}\n\n${sectionByAnchor(text, anchor) ?? `(not found: no heading with anchor #${anchor})`}`;
}

/**
 * The spec section a delivered ID belongs to: `REQ-…-NNN.ACn` → its `### REQ-…-NNN` section in
 * specs/features; `TOOL-NN.ACn` → its `### TOOL-NN` section in plan/tools.md; `NFR-NNN` → its table row.
 */
function requirementSection(root: string, id: string): { key: string; text: string } | undefined {
  const req = /^(REQ-[A-Z]+-\d+)\.AC\d+$/.exec(id)?.[1];
  if (req) {
    const dir = join(root, "specs/features");
    for (const f of existsSync(dir) ? readdirSync(dir).filter((x) => x.endsWith(".md")).sort() : []) {
      const text = readFileSync(join(dir, f), "utf8");
      const heading = new RegExp(`^### (${req}\\b.*)$`, "m").exec(text)?.[1];
      if (heading) return { key: req, text: sectionByAnchor(text, slugify(heading))! };
    }
    return { key: req, text: `### ${req}\n(not found in specs/features)` };
  }
  const tool = /^(TOOL-\d+)\.AC\d+$/.exec(id)?.[1];
  if (tool) {
    const text = read(root, "plan/tools.md") ?? "";
    const heading = new RegExp(`^### (${tool}\\b.*)$`, "m").exec(text)?.[1];
    return { key: tool, text: heading ? sectionByAnchor(text, slugify(heading))! : `### ${tool}\n(not found in plan/tools.md)` };
  }
  if (/^NFR-\d+$/.test(id)) {
    const row = (read(root, "specs/product.md") ?? "").split(/\r?\n/).find((l) => l.startsWith(`| ${id} |`));
    return { key: id, text: `### ${id}\n| ID | Quality | Target | How it's measured |\n|---|---|---|---|\n${row ?? `| ${id} | (not found in specs/product.md) | | |`}` };
  }
  return undefined;
}

function fileBlock(root: string, file: string): string {
  if (file.includes("*")) return `### ${file}\n(a folder of files; open only the ones you need)`;
  const text = read(root, file);
  if (text === undefined) return `### ${file}\n(doesn't exist yet: this task creates it)`;
  const lang = /\.(\w+)$/.exec(file)?.[1] ?? "";
  return `### ${file}\n\n\`\`\`\`${lang}\n${text.trimEnd()}\n\`\`\`\``;
}
