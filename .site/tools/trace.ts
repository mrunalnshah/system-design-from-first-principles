/**
 * TOOL-03 `trace`: writes specs/trace.md, the map from every active criterion (REQ criteria,
 * NFRs and TOOL criteria) to the task that delivers it, that task's status, and the files
 * whose `@req` tags prove it. Generated: never edit specs/trace.md by hand.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadSpecIndex } from "./check.ts";
import { loadPlan } from "./plan.ts";

/** Builds the trace, writes it to `<root>/specs/trace.md`, and returns the Markdown. */
export function trace(root: string): string {
  const spec = loadSpecIndex(root);
  const plan = loadPlan(root);
  const deliveredBy = new Map<string, { id: string; status: string }[]>();
  for (const p of plan.packets) for (const d of Array.isArray(p.fields.delivers) ? p.fields.delivers : []) {
    deliveredBy.set(d, [...(deliveredBy.get(d) ?? []), { id: p.id, status: p.status }]);
  }
  const row = (id: string) => {
    const tasks = deliveredBy.get(id) ?? [];
    const cell = (f: (t: { id: string; status: string }) => string) => tasks.map(f).join(", ") || "—";
    return `| ${id} | ${cell((t) => t.id)} | ${cell((t) => t.status)} | ${(spec.tags.get(id) ?? []).join(", ") || "—"} |`;
  };
  const table = (ids: string[]) => ["| Criterion | Task | Status | Tests tagged @req |", "|---|---|---|---|", ...ids.map(row)].join("\n");
  const reqIds = spec.requirements.filter((r) => !r.deferred).flatMap((r) => r.criteria);
  const nfrIds = [...spec.known].filter((id) => id.startsWith("NFR-")).sort();
  const toolIds = [...spec.known].filter((id) => id.startsWith("TOOL-")).sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
  const text = [
    "# Trace: criteria → tasks → tests",
    "Generated by `npm --prefix .site run tools -- trace`. Don't edit by hand.",
    `${reqIds.length} requirement criteria, ${nfrIds.length} NFRs, ${toolIds.length} tool criteria.`,
    "", "## Requirement criteria", table(reqIds),
    "", "## Non-functional requirements", table(nfrIds),
    "", "## Tool criteria", table(toolIds), "",
  ].join("\n");
  writeFileSync(join(root, "specs/trace.md"), text);
  return text;
}
